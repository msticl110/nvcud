package org.nvcud.ag.lst;

public class cur {
    private Long ud;
    private int curC;

    public cur(Long ud, int curC) {
        this.ud = ud;
        this.curC = curC;
    }

    public Long getUd() {
        return ud;
    }

    public void setUd(Long ud) {
        this.ud = ud;
    }

    public int getCurC() {
        return curC;
    }

    public void setCurC(int curC) {
        this.curC = curC;
    }
}
